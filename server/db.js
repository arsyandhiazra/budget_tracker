// Database: PostgreSQL (di produksi memakai Neon, gratis dan permanen).
//
// - Produksi / Vercel : isi DATABASE_URL, aplikasi tersambung lewat driver "pg".
// - Di laptop         : kalau DATABASE_URL kosong, dipakai PGlite (Postgres yang
//                       tersimpan sebagai folder data/pglite), jadi tidak perlu
//                       memasang apa-apa untuk mencoba.
//
// Bentuk pemakaiannya sengaja dibuat sederhana:
//   await db.get(sql, ...params)     → satu baris (atau undefined)
//   await db.all(sql, ...params)     → semua baris
//   await db.run(sql, ...params)     → { changes }
//   await db.insert(sql, ...params)  → id baris yang baru dibuat
//   await db.tx(async () => { ... }) → semua perintah di dalamnya jadi satu paket
// Tanda tanya (?) di SQL otomatis diubah menjadi $1, $2, ... milik Postgres.
