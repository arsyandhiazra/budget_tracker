// Mengubah "?" menjadi "$1, $2, ..." (tanda tanya di dalam teks bertanda kutip dibiarkan).
export function toPg(sql) {
  let n = 0;
  let inQuote = false;
  let out = '';
  for (const ch of sql) {
    if (ch === "'") inQuote = !inQuote;
    out += ch === '?' && !inQuote ? `$${++n}` : ch;
  }
  return out;
}

// ── Penyambung ke Postgres sungguhan (Neon, Supabase, lokal, dll.) ──
async function connectPg({ url, schema, dropSchemaOnClose, max }) {
  if (schema) {
    // Dipakai tes: tiap tes mendapat "folder" (schema) sendiri di database yang sama.
    const admin = new pg.Client({ connectionString: url });
    await admin.connect();
    await admin.query(`CREATE SCHEMA IF NOT EXISTS "${schema}"`);
    await admin.end();
  }
  const pool = new pg.Pool({
    connectionString: url,
    max,
    idleTimeoutMillis: 10_000,
    connectionTimeoutMillis: 15_000,
    ...(schema ? { options: `-c search_path=${schema}` } : {}),
  });
  pool.on('error', (err) => console.error('Koneksi database terputus:', err.message));
  const wrap = (c) => ({
    query: async (sql, params) => { const r = await c.query(sql, params); return { rows: r.rows, count: r.rowCount }; },
    exec: async (sql) => { await c.query(sql); },
  });
  return {
    kind: 'postgres',
    ...wrap(pool),
    async transaction(fn) {
      const client = await pool.connect();
      try {
        await client.query('BEGIN');
        const result = await fn(wrap(client));
        await client.query('COMMIT');
        return result;
      } catch (err) {
        try { await client.query('ROLLBACK'); } catch { /* koneksi sudah putus */ }
        throw err;
      } finally {
        client.release();
      }
    },
    async close() {
      if (schema && dropSchemaOnClose) {
        await pool.query(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`).catch(() => {});
      }
      await pool.end();
    },
  };
}

// ── Postgres ringan untuk laptop & tes (tanpa memasang apa-apa) ──
async function connectPglite({ dir }) {
  const moduleName = '@electric-sql/pglite'; // sengaja tidak ditulis langsung supaya tidak ikut terbawa ke produksi
  let PGlite;
  try {
    ({ PGlite } = await import(moduleName));
  } catch {
    throw new Error('DATABASE_URL belum diisi. Isi dengan alamat database Postgres kamu (lihat README), atau jalankan "npm install" supaya database lokal tersedia.');
  }
  if (dir) fs.mkdirSync(path.dirname(dir), { recursive: true });
  const lite = new PGlite(dir || undefined);
  const parsers = { [OID_BIGINT]: Number, [OID_NUMERIC]: Number }; // harus per permintaan; opsi di konstruktor tidak berlaku untuk numeric
  await lite.waitReady;

  // PGlite hanya punya satu koneksi, jadi permintaan dilayani satu per satu.
  let chain = Promise.resolve();
  const locked = (fn) => {
    const next = chain.then(() => fn());
    chain = next.catch(() => {});
    return next;
  };
  const wrap = (c) => ({
    query: async (sql, params) => { const r = await c.query(sql, params, { parsers }); return { rows: r.rows, count: r.affectedRows ?? r.rows.length }; },
    exec: async (sql) => { await c.exec(sql); },
  });
  const direct = wrap(lite);
  return {
    kind: 'pglite',
    query: (sql, params) => locked(() => direct.query(sql, params)),
    exec: (sql) => locked(() => direct.exec(sql)),
    transaction: (fn) => locked(async () => {
      await lite.query('BEGIN');
      try {
        const result = await fn(direct);
        await lite.query('COMMIT');
        return result;
      } catch (err) {
        await lite.query('ROLLBACK').catch(() => {});
        throw err;
      }
    }),
    close: () => lite.close(),
  };
}

// Membuka database sesuai pengaturan (config.js). Di production DATABASE_URL wajib diisi,
// karena database lokal hanya untuk mencoba di laptop dan akan hilang di hosting.
export function openDbFromConfig(config, overrides = {}) {
  if (!config.databaseUrl && config.production) {
    throw new Error('DATABASE_URL belum diisi. Buat database gratis di neon.tech lalu isi alamat koneksinya di pengaturan hosting (lihat README).');
  }
  return openDb({ url: config.databaseUrl, pgliteDir: config.pgliteDir, ...overrides });
}

// Nama database untuk ditampilkan di log (tanpa kata sandi).
export function describeDb(config) {
  if (!config.databaseUrl) return `database lokal (${config.pgliteDir})`;
  try { return `Postgres di ${new URL(config.databaseUrl).host}`; } catch { return 'Postgres'; }
}

/**
 * Membuka database lalu merapikan struktur tabelnya.
 * options: { url, pgliteDir, schema, dropSchemaOnClose, max }
 *  - url        : alamat Postgres (DATABASE_URL). Kalau kosong dipakai PGlite.
 *  - pgliteDir  : folder penyimpanan PGlite. Kosong = hanya di memori.
 */
export async function openDb(options = {}) {
  const driver = options.url
    ? await connectPg({ url: options.url, schema: options.schema, dropSchemaOnClose: options.dropSchemaOnClose, max: options.max || 5 })
    : await connectPglite({ dir: options.pgliteDir });

  // Di dalam db.tx(), semua perintah otomatis memakai koneksi yang sama.
  const scope = new AsyncLocalStorage();
  const exec = () => scope.getStore() ?? driver;

  const db = {
    kind: driver.kind,
    all: async (sql, ...params) => (await exec().query(toPg(sql), params)).rows,
    get: async (sql, ...params) => (await exec().query(toPg(sql), params)).rows[0],
    run: async (sql, ...params) => ({ changes: (await exec().query(toPg(sql), params)).count }),
    insert: async (sql, ...params) => (await exec().query(`${toPg(sql)} RETURNING id`, params)).rows[0].id,
    exec: (sql) => exec().exec(sql),
    // Menjalankan beberapa perintah sebagai satu paket: kalau satu gagal,
    // semuanya dibatalkan. Ini yang menjaga jurnal tidak pernah "setengah tersimpan".
    tx(fn) {
      if (scope.getStore()) return fn(); // sudah di dalam paket
      return driver.transaction((conn) => scope.run(conn, fn));
    },
    close: () => driver.close(),
  };

  try {
    await migrate(db);
  } catch (err) {
    await driver.close().catch(() => {});
    throw err;
  }
  return db;
}

async function migrate(db) {
  await db.tx(async () => {
    // Kunci supaya dua server yang menyala bersamaan tidak saling menimpa.
    await db.get('SELECT pg_advisory_xact_lock(727384)');
    await db.exec('CREATE TABLE IF NOT EXISTS schema_migrations (version INTEGER PRIMARY KEY, applied_at TEXT NOT NULL)');
    const done = (await db.get('SELECT COALESCE(MAX(version), 0) AS v FROM schema_migrations')).v;
    for (let i = done; i < MIGRATIONS.length; i += 1) {
      await db.exec(MIGRATIONS[i]);
      await db.run('INSERT INTO schema_migrations (version, applied_at) VALUES (?, ?)', i + 1, nowIso());
    }
  });
}

export const nowIso = () => new Date().toISOString();
